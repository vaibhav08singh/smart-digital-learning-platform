export function searchCourses(query: string): Course[] {
  const q = query.trim().toLowerCase();
  if (!q) return courses;
  return courses.filter((c) =>
    [c.title, c.subjectName, c.instructor, ...c.tags].some((t) => t.toLowerCase().includes(q)),
  );
}
