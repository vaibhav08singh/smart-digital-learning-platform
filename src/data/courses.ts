/** True when a domain is a Computer Science domain. */
export function isCsDomain(domainId: string): boolean {
  return CS_DOMAIN_IDS.has(domainId);
}

export function isCsCourse(course: Pick<Course, "domainId">): boolean {
  return isCsDomain(course.domainId);
}

